function ojLoad(){
  try { var raw = JSON.parse(localStorage.getItem(OJ_KEY)); if (raw && raw.mastered) return raw; } catch(e){}
  return {mastered:{}, planDone:{}};
}
function ojSave(st){
  try { localStorage.setItem(OJ_KEY, JSON.stringify(st)); } catch(e){}
}

/* ---------------- 用户自定义题（localStorage） ---------------- */
var OJ_CUSTOM_KEY = "cppsOjCustomV1";
function ojCustomLoad(){
  try {
    var raw = JSON.parse(localStorage.getItem(OJ_CUSTOM_KEY));
    if (Array.isArray(raw)) return raw;
  } catch(e){}
  return [];
}
function ojCustomSave(list){
  try { localStorage.setItem(OJ_CUSTOM_KEY, JSON.stringify(list)); } catch(e){}
}
