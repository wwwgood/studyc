/* gen-question-bank.js — 将所有现有题目汇总为统一题库格式
 * 用法: node build/gen-question-bank.js
 * 输出: src/scripts/data/question-bank.js
 *
 * 题库格式:
 * { id, subject, module, topicId, kp, q, o, a, why, source, sourceDetail, difficulty, year, region }
 *
 * subject: "english" / "math" / "chinese" / "other"
 * source: "自编" 或 "真题"
 * 后续可通过 import-questions.js 导入真实真题替换/扩充
 */
var fs = require("fs");
var path = require("path");

var questions = [];
var qid = 0;
function nextId(){ qid++; return "qb" + String(qid).padStart(5, "0"); }

/* ===== 1. 从 TOPIC_EXAM_DATA 导入（专题真题，标记为自编） ===== */
var topicCode = fs.readFileSync(path.join(__dirname, "..", "src", "scripts", "data", "english-topic-exam.js"), "utf8");
eval(topicCode);

Object.keys(TOPIC_EXAM_DATA.grammar).forEach(function(chId){
  TOPIC_EXAM_DATA.grammar[chId].forEach(function(q){
    questions.push({
      id: nextId(), subject: "english", module: "grammar", topicId: parseInt(chId),
      kp: [], q: q.q, o: q.o, a: q.a, why: q.why,
      source: "自编", sourceDetail: "按小升初语法知识点编写",
      difficulty: 2, year: 0, region: ""
    });
  });
});

Object.keys(TOPIC_EXAM_DATA.vocab).forEach(function(uId){
  TOPIC_EXAM_DATA.vocab[uId].forEach(function(q){
    questions.push({
      id: nextId(), subject: "english", module: "vocab", topicId: parseInt(uId),
      kp: [], q: q.q, o: q.o, a: q.a, why: q.why,
      source: "自编", sourceDetail: "按词汇主题编写",
      difficulty: 2, year: 0, region: ""
    });
  });
});

TOPIC_EXAM_DATA.reading.forEach(function(q){
  questions.push({
    id: nextId(), subject: "english", module: "reading", topicId: 0,
    kp: [], q: q.q, o: q.o, a: q.a, why: q.why,
    source: "自编", sourceDetail: "阅读理解技巧题",
    difficulty: 2, year: 0, region: ""
  });
});

TOPIC_EXAM_DATA.writing.forEach(function(q){
  questions.push({
    id: nextId(), subject: "english", module: "writing", topicId: 0,
    kp: [], q: q.q, o: q.o, a: q.a, why: q.why,
    source: "自编", sourceDetail: "作文技巧题",
    difficulty: 2, year: 0, region: ""
  });
});

/* ===== 2. 从 EXAM_DATA 导入（综合真题卷，标记为自编） ===== */
var examCode = fs.readFileSync(path.join(__dirname, "..", "src", "scripts", "data", "english-exam.js"), "utf8");
eval(examCode);

EXAM_DATA.papers.forEach(function(paper){
  paper.questions.forEach(function(q){
    questions.push({
      id: nextId(), subject: "english", module: "exam", topicId: paper.cat,
      kp: [], q: q.q, o: q.o, a: q.a, why: q.why,
      source: "自编", sourceDetail: paper.name,
      difficulty: 3, year: 0, region: ""
    });
  });
});

/* ===== 3. 从 EQ_DATA 练习题导入（语法闯关练习题） ===== */
var grammarCode = fs.readFileSync(path.join(__dirname, "..", "src", "scripts", "data", "english-grammar.js"), "utf8");
eval(grammarCode);
EQ_DATA.lessons.forEach(function(lesson){
  (lesson.q || []).forEach(function(q){
    questions.push({
      id: nextId(), subject: "english", module: "grammar", topicId: lesson.ch,
      kp: [lesson.t], q: q.q, o: q.o, a: q.a, why: q.why || "",
      source: "自编", sourceDetail: "语法闯关练习题: " + lesson.t,
      difficulty: q.lv || 1, year: 0, region: ""
    });
  });
});

/* ===== 输出 ===== */
var out = "// AUTO-GENERATED by build/gen-question-bank.js — 统一题库\n";
out += "// 共 " + questions.length + " 道题\n";
out += "// source: 自编/真题 — 后续通过 import-questions.js 导入真实真题替换/扩充\n";
out += "var QB_DATA = {\n";
out += "  questions: " + JSON.stringify(questions, null, 2) + "\n";
out += "};\n";

var outPath = path.join(__dirname, "..", "src", "scripts", "data", "question-bank.js");
fs.writeFileSync(outPath, out, "utf8");

var byModule = {};
questions.forEach(function(q){ byModule[q.module] = (byModule[q.module] || 0) + 1; });
var bySource = {};
questions.forEach(function(q){ bySource[q.source] = (bySource[q.source] || 0) + 1; });

console.log("Generated " + outPath);
console.log("Total questions: " + questions.length);
console.log("By module:", JSON.stringify(byModule));
console.log("By source:", JSON.stringify(bySource));