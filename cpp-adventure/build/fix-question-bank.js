/*
 * 内置题库整治脚本（一次性）：node build/fix-question-bank.js
 * 1. sourceDetail 去掉"真题"字样 —— 这批题是按真题风格自编的仿真题，不能挂真题名误导
 * 2. 补 type:"choice" 字段（683 题全部有 4 个选项，按 qtypes.js 约定显式标注）
 * 3. 修生成器笔误干扰项：tomatoos（旁边已有 tomatos，改为 plausible 的 tomato's）
 * 4. 更新头注释
 * 跑完自动校验；可重复执行（幂等）。
 */
const fs = require("fs");
const path = require("path");

const FILE = path.join(__dirname, "..", "src", "scripts", "data", "question-bank.js");
let text = fs.readFileSync(FILE, "utf8");
const before = text;

/* 1. sourceDetail 去掉"真题"字样 */
text = text.replace(/小升初英语真题·/g, "小升初英语仿真卷·");

/* 2. 补 type:"choice"：插在每个 "a": N, 行之前（题库所有题都有选项） */
text = text.replace(/^(\s*)"a": (\d+),$/gm, (m, indent, num) => `${indent}"type": "choice",\n${indent}"a": ${num},`);

/* 3. 生成器笔误干扰项 */
text = text.replace(/"tomatoos"/g, '"tomato\'s"');

/* 4. 头注释 */
text = text.replace(
  /\/\/ AUTO-GENERATED by build\/gen-question-bank\.js — 统一题库\n\/\/ 共 \d+ 道题\n\/\/ source: 自编\/真题 — 后续通过 import-questions\.js 导入真实真题替换\/扩充/,
  "// AUTO-GENERATED by build/gen-question-bank.js — 统一题库（已由 build/fix-question-bank.js 整治）\n// 全部为按真题风格自编的仿真题（source=自编），不含真实真题\n// 所有题目均显式标注 type:choice；真实真题请通过「题库管理→导入真题」导入"
);

if (text === before){
  console.log("没有需要修改的内容（可能已整治过）");
} else {
  fs.writeFileSync(FILE, text, "utf8");
  console.log("已写入 " + FILE);
}

/* ---- 校验 ---- */
global.window = global;
try {
  eval(fs.readFileSync(FILE, "utf8"));
} catch(e){
  console.error("校验失败：文件无法解析 -", e.message);
  process.exit(1);
}
const qs = QB_DATA.questions;
let errs = 0;
qs.forEach((q, i) => {
  if (q.type !== "choice"){ console.error(`#${i} ${q.id} 缺 type`); errs++; }
  if (!q.q || !q.q.trim()){ console.error(`#${i} ${q.id} 无题干`); errs++; }
  if (!q.o || q.o.length < 2){ console.error(`#${i} ${q.id} 选项不足`); errs++; }
  if (typeof q.a !== "number" || q.a < 0 || q.a >= q.o.length){ console.error(`#${i} ${q.id} 答案越界`); errs++; }
  if (/真题/.test(q.sourceDetail || "")){ console.error(`#${i} ${q.id} sourceDetail 仍含"真题"`); errs++; }
});
console.log(`校验完成：共 ${qs.length} 题，${errs ? errs + " 个问题" : "全部通过"}`);
process.exit(errs ? 1 : 0);
