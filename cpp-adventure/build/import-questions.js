/* import-questions.js — 从文本文件导入真题到题库
 * 用法:
 *   node build/import-questions.js <input.txt> [--module=grammar] [--topic=1] [--source=真题] [--year=2023] [--region=北京]
 *
 * 输入文件格式（每题一段，空行分隔）:
 * 1. 题干文本___?
 * A. 选项A   B. 选项B   C. 选项C   D. 选项D
 * 答案：C
 * 解析：解析文本
 *
 * 也支持 JSON 格式输入:
 * [{ "q": "...", "o": ["A","B","C","D"], "a": 2, "why": "..." }, ...]
 *
 * 输出: 追加到 src/scripts/data/question-bank.js
 */
var fs = require("fs");
var path = require("path");

var args = process.argv.slice(2);
if (args.length === 0){
  console.log("用法: node build/import-questions.js <input.txt> [options]");
  console.log("  --module=grammar/vocab/reading/writing/exam  (默认: grammar)");
  console.log("  --topic=1          (章节/单元ID, 默认: 0)");
  console.log("  --source=真题      (来源标记, 默认: 真题)");
  console.log("  --detail=...       (来源详情, 如 '2023年北京小升初')");
  console.log("  --year=2023        (年份)");
  console.log("  --region=北京      (地区)");
  console.log("  --difficulty=3     (难度1-5, 默认: 3)");
  process.exit(1);
}

var inputFile = args[0];
var opts = { module: "grammar", topicId: 0, source: "真题", sourceDetail: "", year: 0, region: "", difficulty: 3 };
args.slice(1).forEach(function(a){
  var m = a.match(/^--(\w+)=(.*)$/);
  if (m){
    var key = m[1], val = m[2];
    if (key === "topic" || key === "year" || key === "difficulty") opts[key === "topic" ? "topicId" : key] = parseInt(val) || 0;
    else if (key === "detail") opts.sourceDetail = val;
    else if (opts.hasOwnProperty(key)) opts[key] = val;
  }
});

var content = fs.readFileSync(inputFile, "utf8");
var newQuestions = [];

// 尝试 JSON 格式
try {
  var json = JSON.parse(content);
  if (Array.isArray(json)){
    json.forEach(function(item){
      newQuestions.push({
        module: item.module || opts.module,
        topicId: item.topicId || opts.topicId,
        kp: item.kp || [],
        q: item.q, o: item.o, a: item.a, why: item.why || "",
        source: item.source || opts.source,
        sourceDetail: item.sourceDetail || opts.sourceDetail,
        difficulty: item.difficulty || opts.difficulty,
        year: item.year || opts.year,
        region: item.region || opts.region
      });
    });
  }
} catch(e){
  // 不是 JSON，按文本格式解析
  newQuestions = parseTextFormat(content, opts);
}

if (newQuestions.length === 0){
  console.log("未解析到题目，请检查文件格式。");
  process.exit(1);
}

// 读取现有题库
var bankPath = path.join(__dirname, "..", "src", "scripts", "data", "question-bank.js");
var bankCode = fs.readFileSync(bankPath, "utf8");
eval(bankCode);

// 生成新ID
var maxId = 0;
QB_DATA.questions.forEach(function(q){
  var n = parseInt((q.id || "").replace("qb", ""), 10);
  if (n > maxId) maxId = n;
});

newQuestions.forEach(function(q){
  maxId++;
  q.id = "qb" + String(maxId).padStart(5, "0");
  QB_DATA.questions.push(q);
});

// 写回题库
var out = "// AUTO-GENERATED by build/gen-question-bank.js + import-questions.js\n";
out += "// 共 " + QB_DATA.questions.length + " 道题\n";
out += "var QB_DATA = " + JSON.stringify({ questions: QB_DATA.questions }, null, 2) + ";\n";
fs.writeFileSync(bankPath, out, "utf8");

console.log("导入 " + newQuestions.length + " 道题，题库总计 " + QB_DATA.questions.length + " 道");
console.log("来源: " + opts.source + (opts.sourceDetail ? " - " + opts.sourceDetail : ""));

function parseTextFormat(text, opts){
  var questions = [];
  // 按空行分段
  var blocks = text.split(/\n\s*\n/);
  blocks.forEach(function(block){
    block = block.trim();
    if (!block) return;
    // 提取题干（第一行，去掉序号）
    var lines = block.split("\n").map(function(l){ return l.trim(); }).filter(function(l){ return l; });
    if (lines.length < 2) return;

    var qLine = lines[0].replace(/^\d+[\.\、]\s*/, "");
    // 提取选项
    var optLine = lines.find(function(l){ return /[A-D][\.\、]/.test(l); });
    if (!optLine) return;

    var opts_arr = [];
    var optRegex = /([A-D])[\.\、]\s*([^\n]*?)(?=\s+[A-D][\.\、]|$)/g;
    // 尝试单行多选项
    var m;
    while ((m = optRegex.exec(optLine)) !== null){
      opts_arr.push(m[2].trim());
    }
    // 如果没匹配到，尝试每行一个选项
    if (opts_arr.length < 2){
      opts_arr = [];
      lines.forEach(function(l){
        var mm = l.match(/^[A-D][\.\、]\s*(.*)$/);
        if (mm) opts_arr.push(mm[1].trim());
      });
    }
    if (opts_arr.length < 2) return;

    // 提取答案
    var ansLine = lines.find(function(l){ return /答案|answer/i.test(l); });
    var ans = 0;
    if (ansLine){
      var am = ansLine.match(/[答案：:\s]*([A-Da-d])/);
      if (am) ans = am[1].toUpperCase().charCodeAt(0) - 65;
    }

    // 提取解析
    var whyLine = lines.find(function(l){ return /解析|解释|why/i.test(l); });
    var why = whyLine ? whyLine.replace(/^.*[解析|解释|why][:：\s]*/, "").trim() : "";

    questions.push({
      module: opts.module, topicId: opts.topicId, kp: [],
      q: qLine, o: opts_arr, a: ans, why: why,
      source: opts.source, sourceDetail: opts.sourceDetail,
      difficulty: opts.difficulty, year: opts.year, region: opts.region
    });
  });
  return questions;
}